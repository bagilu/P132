-- P132 SQL17E
-- Foreign Linguistic Analysis Architecture
-- External language-specific analyzers produce linguistic observations.
-- PostgreSQL stores versioned analysis and materializes selected learning terms.
--
-- Architecture:
-- Foreign Article -> Analysis Run -> Token/POS/Lemma/NER -> Term Candidates
-- -> conservative acceptance -> ForeignTermOccurrence -> Lexicon mapping -> learner evidence
--
-- IMPORTANT:
-- * Analyzer output is annotation, not learner evidence.
-- * Re-analysis may supersede annotation; Exposure/Evidence history is preserved.
-- * English and Japanese may use different analyzers/models under one contract.
-- * No external NLP service is called from PostgreSQL.

create table if not exists public."TblP132ForeignAnalysisRun"(
 "AnalysisRunID" bigint generated by default as identity primary key,
 "ArticleID" bigint not null references public."TblP132Article"("ArticleID") on delete cascade,
 "LanguageCode" text not null check("LanguageCode" in('en','ja')),
 "AnalyzerName" text not null,
 "AnalyzerVersion" text not null,
 "ModelName" text,
 "ModelVersion" text,
 "PipelineVersion" text not null default 'P132-LING-0.1',
 "ContentHash" text,
 "Status" text not null default 'pending'
   check("Status" in('pending','running','completed','failed','superseded')),
 "StartedAt" timestamptz,
 "CompletedAt" timestamptz,
 "ErrorMessage" text,
 "Metadata" jsonb not null default '{}'::jsonb,
 "CreatedAt" timestamptz not null default now()
);
create index if not exists "IdxP132ForeignAnalysisRunArticle"
 on public."TblP132ForeignAnalysisRun"("ArticleID","CreatedAt" desc);

create table if not exists public."TblP132ForeignLinguisticToken"(
 "LinguisticTokenID" bigint generated by default as identity primary key,
 "AnalysisRunID" bigint not null references public."TblP132ForeignAnalysisRun"("AnalysisRunID") on delete cascade,
 "TokenIndex" integer not null check("TokenIndex">=0),
 "SentenceIndex" integer,
 "SurfaceText" text not null,
 "Lemma" text,
 "UniversalPOS" text,
 "LanguagePOS" text,
 "Morphology" jsonb not null default '{}'::jsonb,
 "StartOffset" integer not null check("StartOffset">=0),
 "EndOffset" integer not null check("EndOffset">"StartOffset"),
 "EntityType" text,
 "IsStopword" boolean,
 "Confidence" numeric(5,4) check("Confidence" is null or "Confidence" between 0 and 1),
 unique("AnalysisRunID","TokenIndex"),
 unique("AnalysisRunID","StartOffset","EndOffset")
);
create index if not exists "IdxP132ForeignLinguisticTokenRunOffset"
 on public."TblP132ForeignLinguisticToken"("AnalysisRunID","StartOffset");

create table if not exists public."TblP132ForeignTermCandidate"(
 "ForeignTermCandidateID" bigint generated by default as identity primary key,
 "AnalysisRunID" bigint not null references public."TblP132ForeignAnalysisRun"("AnalysisRunID") on delete cascade,
 "SurfaceText" text not null,
 "NormalizedTerm" text not null,
 "Lemma" text,
 "StartOffset" integer not null check("StartOffset">=0),
 "EndOffset" integer not null check("EndOffset">"StartOffset"),
 "TermKind" text not null check("TermKind" in
   ('term','multiword','proper_noun','fixed_expression','function_word')),
 "CandidateMethod" text not null check("CandidateMethod" in
   ('token','noun_chunk','named_entity','mwe','morphology','dictionary','analyzer','manual')),
 "POSPattern" text,
 "Confidence" numeric(5,4) check("Confidence" is null or "Confidence" between 0 and 1),
 "SelectionStatus" text not null default 'candidate'
   check("SelectionStatus" in('candidate','accepted','rejected','superseded')),
 "SelectionReason" text,
 "CreatedAt" timestamptz not null default now(),
 unique("AnalysisRunID","StartOffset","EndOffset","CandidateMethod")
);
create index if not exists "IdxP132ForeignTermCandidateRun"
 on public."TblP132ForeignTermCandidate"("AnalysisRunID","StartOffset");

-- Provenance bridge: one materialized reading occurrence can be traced to the
-- linguistic analysis/candidate that created it. This avoids changing the 17A
-- occurrence table in a way that would disturb existing learner evidence.
create table if not exists public."TblP132ForeignOccurrenceProvenance"(
 "ForeignTermOccurrenceID" bigint primary key
   references public."TblP132ForeignTermOccurrence"("ForeignTermOccurrenceID") on delete cascade,
 "AnalysisRunID" bigint not null
   references public."TblP132ForeignAnalysisRun"("AnalysisRunID") on delete restrict,
 "ForeignTermCandidateID" bigint
   references public."TblP132ForeignTermCandidate"("ForeignTermCandidateID") on delete set null,
 "MaterializerVersion" text not null default 'P132-LING-MAT-0.1',
 "CreatedAt" timestamptz not null default now()
);
create index if not exists "IdxP132ForeignOccurrenceProvenanceRun"
 on public."TblP132ForeignOccurrenceProvenance"("AnalysisRunID");

