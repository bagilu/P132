-- Reader-facing canonical view: linguistic/NLP annotation outranks heuristic rule
-- annotation when spans overlap; manual/lexicon remain authoritative. Then prefer
-- longer spans within the same authority tier.
create or replace view public."VwP132ForeignReadingTerm" as
select o.*
from public."TblP132ForeignTermOccurrence" o
where o."IsActive"
and not exists(
 select 1 from public."TblP132ForeignTermOccurrence" z
 where z."ArticleID"=o."ArticleID" and z."IsActive"
   and z."StartOffset"<o."EndOffset" and z."EndOffset">o."StartOffset"
   and (
     case z."AnnotationMethod" when 'manual' then 5 when 'lexicon' then 4
          when 'nlp' then 3 when 'ai' then 2 else 1 end
       > case o."AnnotationMethod" when 'manual' then 5 when 'lexicon' then 4
          when 'nlp' then 3 when 'ai' then 2 else 1 end
     or (
       case z."AnnotationMethod" when 'manual' then 5 when 'lexicon' then 4
            when 'nlp' then 3 when 'ai' then 2 else 1 end
       = case o."AnnotationMethod" when 'manual' then 5 when 'lexicon' then 4
            when 'nlp' then 3 when 'ai' then 2 else 1 end
       and (z."EndOffset"-z."StartOffset")>(o."EndOffset"-o."StartOffset")
     )
   )
);
revoke all on public."VwP132ForeignReadingTerm" from public,anon,authenticated;
grant select on public."VwP132ForeignReadingTerm" to service_role;

-- IMPORTANT reader fix: 17C originally read every active raw occurrence.
-- From SQL17E onward it must read the canonical non-overlapping view, otherwise
-- raw tokens and multiword/NLP spans would both receive red/green controls.
create or replace function public."P132_GetForeignArticleTerms"(p_article_id bigint,p_reading_session_id uuid)
returns jsonb language plpgsql security definer set search_path=public,pg_temp as $$
declare uid uuid:=auth.uid(); a public."TblP132Article"; r record; eid bigint; arr jsonb:='[]'::jsonb; meaning text;
begin
 if uid is null then raise exception 'Authentication required'; end if;
 select * into a from public."TblP132Article"
 where "ArticleID"=p_article_id and "IsPublished" and "LanguageCode" in('en','ja');
 if not found then raise exception 'Foreign article not found'; end if;
 if not exists(select 1 from public."TblP132ReadingSession" s
   where s."ReadingSessionID"=p_reading_session_id and s."UserID"=uid
     and s."ArticleID"=p_article_id and s."EndedAt" is null)
   then raise exception 'Invalid reading session'; end if;

 for r in
   select o.*,s."LatestEvidenceType"
   from public."VwP132ForeignReadingTerm" o
   left join public."TblP132LearnerForeignTermState" s on s."UserID"=uid
    and s."LanguageCode"=o."LanguageCode" and s."NormalizedTerm"=o."NormalizedTerm"
   where o."ArticleID"=p_article_id
   order by o."StartOffset"
 loop
   select "ForeignTermExposureID" into eid from public."TblP132ForeignTermExposure"
   where "ReadingSessionID"=p_reading_session_id
     and "ForeignTermOccurrenceID"=r."ForeignTermOccurrenceID";
   if eid is null then
     insert into public."TblP132ForeignTermExposure"
     ("UserID","ReadingSessionID","ArticleID","ForeignTermOccurrenceID","ConceptID","LanguageCode","NormalizedTerm",
      "AlgorithmVersion")
     values(uid,p_reading_session_id,p_article_id,r."ForeignTermOccurrenceID",r."ConceptID",
      r."LanguageCode",r."NormalizedTerm",'P132-FOREIGN-0.2')
     returning "ForeignTermExposureID" into eid;
   end if;
   select coalesce(pm."MeaningZh",c."MeaningZh",c."CanonicalZh") into meaning
   from (select 1) z
   left join public."TblP132PersonalTermMeaning" pm on pm."UserID"=uid
      and pm."LanguageCode"=r."LanguageCode" and pm."NormalizedTerm"=r."NormalizedTerm" and pm."IsActive"
   left join public."TblP132VocabularyConcept" c on c."ConceptID"=r."ConceptID";
   arr:=arr||jsonb_build_array(jsonb_build_object(
    'foreign_term_occurrence_id',r."ForeignTermOccurrenceID",'exposure_id',eid,
    'surface_text',r."SurfaceText",'normalized_term',r."NormalizedTerm",
    'start_offset',r."StartOffset",'end_offset',r."EndOffset",
    'term_kind',r."TermKind",'meaning_zh',meaning,
    'annotation_method',r."AnnotationMethod",'annotation_version',r."AnnotationVersion",
    'show_translation',true,
    'show_understand',coalesce(r."LatestEvidenceType",'')<>'understand'));
 end loop;
 return jsonb_build_object('article_id',p_article_id,'language',a."LanguageCode",
   'algorithm_version','P132-FOREIGN-0.2','terms',arr);
end $$;
revoke all on function public."P132_GetForeignArticleTerms"(bigint,uuid) from public,anon;
grant execute on function public."P132_GetForeignArticleTerms"(bigint,uuid) to authenticated;

